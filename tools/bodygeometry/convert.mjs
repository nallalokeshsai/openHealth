// Converts the MuscleMap geometry (MIT, via openGym's body-paths.js) into the compact
// TSV that `ui/src/main/res/raw/body_paths.tsv` ships and `OhBodyGeometry` parses.
//
//   node tools/bodygeometry/convert.mjs
//
// Only the path geometry crosses: openGym's renderer, recovery logic and component code
// are not used (`BUILD-ROADMAP.md` §B4, `DESIGN.md` §9.1, Appendix C). Whole muscles are
// kept as MuscleMap generated them; openGym's `body-geometry.js` split (lats, deltoid
// heads) is deliberately not applied, because `DESIGN.md` §9.1 requires whole muscles and
// a sub-region would imply a precision the exercise data does not have.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import PATHS from './upstream/body-paths.js'

const here = dirname(fileURLToPath(import.meta.url))
const OUT = resolve(here, '../../ui/src/main/res/raw/body_paths.tsv')

const HEADER = [
  '# MuscleMap geometry (MIT, Melih Colpan, via openGym body-paths.js).',
  '# Generated by tools/bodygeometry/convert.mjs — do not hand-edit.',
  '# view<TAB>male|female.front|back<TAB>viewBoxX<TAB>viewBoxY<TAB>width<TAB>height',
  '# part<TAB>view<TAB>muscleKey<TAB>svgPath',
]

const lines = [...HEADER]
const counts = {}
for (const [sex, sides] of Object.entries(PATHS)) {
  for (const [side, view] of Object.entries(sides)) {
    const viewName = `${sex}.${side}`
    const [x, y, w, h] = view.vb.trim().split(/\s+/).map(Number)
    if (![x, y, w, h].every(Number.isFinite)) throw new Error(`bad viewBox for ${viewName}`)
    lines.push(['view', viewName, x, y, w, h].join('\t'))
    for (const [key, paths] of Object.entries(view.p)) {
      if (!Array.isArray(paths) || paths.length === 0) throw new Error(`no paths for ${viewName}.${key}`)
      for (const d of paths) {
        if (d.includes('\t') || d.includes('\n')) throw new Error(`path needs escaping: ${viewName}.${key}`)
        lines.push(['part', viewName, key, d].join('\t'))
        counts[key] = (counts[key] || 0) + 1
      }
    }
  }
}

writeFileSync(OUT, lines.join('\n') + '\n')
console.log(`wrote ${OUT} (${lines.length - HEADER.length} rows, ${Object.keys(counts).length} part keys)`)
