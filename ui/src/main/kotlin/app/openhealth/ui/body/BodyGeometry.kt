/**
 * The MuscleMap geometry (`DESIGN.md` §9.1, Appendix C): four views, each a viewBox and one
 * or more path lists per part. Only the path data is upstream (MIT, notice in `NOTICE.md`);
 * this loader, the renderer, the layers and the interaction are ours.
 *
 * The TSV is generated by `tools/bodygeometry/convert.mjs` and read from `res/raw`, so the
 * file grows the APK by one plain-text asset and needs no JSON parser. Parsing happens
 * once per process, off the first frame (`DESIGN.md` Appendix B).
 */
@Immutable
data class GeometryPart(
    /** The MuscleMap key, e.g. `forearm`. */
    val key: String,
    /** The whole muscle it draws, or null for the silhouette (head, hands, feet …). */
    val muscle: Muscle?,
    val paths: List<AndroidPath>,
    val bounds: android.graphics.RectF,
)

@Immutable
data class GeometryView(val view: BodyView, val viewBox: ViewBox, val parts: List<GeometryPart>) {
    /**
     * The hit regions of this view, rasterised once. Building them walks every path, so
     * it is done on first touch and kept with the view it belongs to (`DESIGN.md` §9.1).
     */
    val hitRegions: Map<Muscle, Region> by lazy { buildHitRegions(this) }
}

data class ViewBox(val x: Float, val y: Float, val width: Float, val height: Float) {
    val aspectRatio: Float get() = width / height
}

/** The four views, keyed by [BodyView], parsed once and cached. */
class BodyGeometry private constructor(val views: Map<BodyView, GeometryView>) {
    fun view(sex: BodySex, side: BodySide): GeometryView? = views[BodyView(sex, side)]

    /** Every muscle shape in a view, in one path, for hit-testing and the fat clip. */
    fun muscleUnion(view: GeometryView): AndroidPath = AndroidPath().apply {
        view.parts.filter { it.muscle != null }.forEach { part -> part.paths.forEach(::addPath) }
    }

    companion object {
        private const val PATH_COLUMNS = 4
        private const val VIEW_COLUMNS = 6
        private const val INDEX_VIEW = 1
        private const val INDEX_KEY = 2
        private const val INDEX_DATA = 3
        private const val VIEW_NAME = 1
        private const val VIEW_X = 2
        private const val VIEW_Y = 3
        private const val VIEW_W = 4
        private const val VIEW_H = 5

        @Volatile
        private var cached: BodyGeometry? = null

        /** The parsed geometry, or null while the first read is still in progress. */
        fun cached(): BodyGeometry? = cached

        /**
         * Reads and parses the resource. Call from an IO dispatcher: it is a 100 KB text
         * file and about a thousand path commands (`DESIGN.md` Appendix B).
         */
        fun load(context: Context): BodyGeometry {
            cached?.let { return it }
            val text = context.resources.openRawResource(R.raw.body_paths)
                .bufferedReader(Charsets.UTF_8)
                .use { it.readText() }
            return parse(text).also { cached = it }
        }

        fun parse(text: String): BodyGeometry {
            val viewBoxes = mutableMapOf<String, ViewBox>()
            val parts = mutableMapOf<String, MutableList<GeometryPart>>()
            text.lineSequence().forEach { line ->
                if (line.isBlank() || line.startsWith("#")) return@forEach
                val cells = line.split('\t')
                when (cells[0]) {
                    "view" -> {
                        require(cells.size == VIEW_COLUMNS) {
                            "Bad view row with ${cells.size} columns: ${cells.firstOrNull()}"
                        }
                        viewBoxes[cells[VIEW_NAME]] = ViewBox(
                            x = cells[VIEW_X].toFloat(),
                            y = cells[VIEW_Y].toFloat(),
                            width = cells[VIEW_W].toFloat(),
                            height = cells[VIEW_H].toFloat(),
                        )
                    }

                    "part" -> {
                        require(cells.size == PATH_COLUMNS) {
                            "Bad part row with ${cells.size} columns: ${cells.firstOrNull()}"
                        }
                        val key = cells[INDEX_KEY]
                        val path = androidx.compose.ui.graphics.vector.PathParser()
                            .parsePathString(cells[INDEX_DATA])
                            .toPath(Path())
                            .asAndroidPath()
                        val bounds = android.graphics.RectF()
                        path.computeBounds(bounds, true)
                        val muscle = Muscle.fromKey(key)
                        require(muscle != null || key in BODY_INERT_PARTS) {
                            "Geometry key '$key' is neither a whole muscle nor a silhouette part"
                        }
                        parts.getOrPut(cells[INDEX_VIEW]) { mutableListOf() } += GeometryPart(
                            key = key,
                            muscle = muscle,
                            paths = listOf(path),
                            bounds = bounds,
                        )
                    }
                }
            }
            val views = viewBoxes.mapNotNull { (name, box) ->
                val view = parseView(name) ?: return@mapNotNull null
                view to GeometryView(
                    view = view,
                    viewBox = box,
                    parts = mergeParts(parts[name].orEmpty()),
                )
            }.toMap()
            require(views.size == EXPECTED_VIEWS) {
                "Expected four body views, found ${views.size}"
            }
            return BodyGeometry(views)
        }

        private const val EXPECTED_VIEWS = 4

        private fun mergeParts(parts: List<GeometryPart>): List<GeometryPart> = parts
            .groupBy { it.key }
            .map { (key, group) ->
                val bounds = android.graphics.RectF()
                group.forEach { bounds.union(it.bounds) }
                group.first().copy(
                    paths = group.flatMap { it.paths },
                    bounds = bounds,
                )
            }

        private val VIEW_NAMES: Map<String, BodyView> = BodySex.entries
            .flatMap { sex ->
                BodySide.entries.map { side ->
                    "${sex.name.lowercase()}.${side.name.lowercase()}" to BodyView(sex, side)
                }
            }
            .toMap()

        private fun parseView(name: String): BodyView? = VIEW_NAMES[name.lowercase()]
    }
}

/**
 * The adipose band (`DESIGN.md` §9.1.1): each region's outline stroked by its thickness and
 * cut against the union of every muscle, so the band exists **only outside** the muscle
 * shapes. A recovery colour can therefore never sit on fat, and a pale fat edge can never
 * be read as a recovery step.
 */
object AdiposeGeometry {
    private const val STROKE_FACTOR = 2f
    private const val KEY_SCALE = 10f

    /**
     * How many bands are kept. The band is expensive to build and cheap to hold, but a
     * scrub of body fat or a tape measurement (the debug harness, and the before/after
     * slider of `DESIGN.md` §9.1.1) asks for a new thickness on every frame, so the
     * cache is bounded rather than unbounded: four views, twice over, least recently
     * used first out.
     */
    private const val CACHE_ENTRIES = 8

    private val cache = object : LinkedHashMap<String, AndroidPath>(CACHE_ENTRIES, LOAD, true) {
        override fun removeEldestEntry(eldest: Map.Entry<String, AndroidPath>): Boolean =
            size > CACHE_ENTRIES
    }

    private const val LOAD = 0.75f

    /** The band for a view at these thicknesses, cached across recompositions and rotation. */
    fun cached(view: GeometryView, thickness: Map<MuscleRegion, Float>): AndroidPath? =
        synchronized(cache) { cache[key(view, thickness)] }

    fun store(view: GeometryView, thickness: Map<MuscleRegion, Float>, band: AndroidPath) {
        synchronized(cache) { cache[key(view, thickness)] = band }
    }

    private fun key(view: GeometryView, thickness: Map<MuscleRegion, Float>): String =
        view.view.toString() + "|" + thickness.entries.sortedBy { it.key.ordinal }
            .joinToString(",") { "${it.key.name}=${(it.value * KEY_SCALE).toInt()}" }

    /**
     * How wide a seam between two muscle paths is closed before the band is built:
     * 24 viewBox units (about 5.6 dp on a 300 dp figure), wide enough to bridge the gaps
     * in the MuscleMap paths, including the neck and shoulder seams, and far narrower
     * than a limb.
     */
    const val SEAM_UNITS = 24f

    /**
     * The adipose layer: one band around the body's outline, never under a muscle and
     * never inside the silhouette (`DESIGN.md` §9.1.1).
     *
     * The muscle paths do not touch, so the raw union's outline runs down every seam
     * between neighbouring muscles. Closing that union with a narrow ring before the
     * band is built fills those seams into the silhouette, so the band is drawn only on
     * the body's outside edge and never as a gold line between two abs. A region thicker
     * than the thinnest one adds an outward ring beyond that rim, which is how a waist
     * reads thicker than a forearm.
     */
    fun layer(view: GeometryView, thickness: Map<MuscleRegion, Float>): AndroidPath {
        val muscleUnion = AndroidPath().apply {
            view.parts.filter { it.muscle != null }.forEach { part ->
                part.paths.forEach(::addPath)
            }
        }
        val silhouette = AndroidPath().apply {
            addPath(muscleUnion)
            addPath(strokeOutline(muscleUnion, SEAM_UNITS / 2f))
        }
        val base = thickness.values.filter { it > 0f }.minOrNull() ?: return AndroidPath()
        val rim = strokeOutline(silhouette, base)
        val byRegion = view.parts
            .filter { it.muscle != null }
            .groupBy { it.muscle!!.region }
        thickness.forEach { (region, outward) ->
            if (outward <= base) return@forEach
            val parts = byRegion[region] ?: return@forEach
            val union = AndroidPath().apply { parts.forEach { p -> p.paths.forEach(::addPath) } }
            val extra = strokeOutline(union, outward)
            extra.op(rim, AndroidPath.Op.DIFFERENCE)
            extra.op(silhouette, AndroidPath.Op.DIFFERENCE)
            rim.op(extra, AndroidPath.Op.UNION)
        }
        rim.op(silhouette, AndroidPath.Op.DIFFERENCE)
        return rim
    }

    private fun strokeOutline(path: AndroidPath, outward: Float): AndroidPath {
        val paint = Paint().apply {
            style = Paint.Style.STROKE
            strokeWidth = outward * STROKE_FACTOR
            strokeCap = Paint.Cap.ROUND
            strokeJoin = Paint.Join.ROUND
            isAntiAlias = true
        }
        val band = AndroidPath()
        paint.getFillPath(path, band)
        return band
    }
}

/**
 * A muscle's tappable area, in viewBox coordinates; built once per parsed view and held
 * by that view, so a second geometry can never be handed the first one's regions.
 */
fun bodyHitRegions(view: GeometryView): Map<Muscle, Region> = view.hitRegions

private fun buildHitRegions(view: GeometryView): Map<Muscle, Region> {
    val bounds = Region(
        view.viewBox.x.toInt(),
        view.viewBox.y.toInt(),
        (view.viewBox.x + view.viewBox.width).toInt(),
        (view.viewBox.y + view.viewBox.height).toInt(),
    )
    return view.parts.mapNotNull { part ->
        val muscle = part.muscle ?: return@mapNotNull null
        val region = Region()
        part.paths.forEach { path ->
            val one = Region()
            one.setPath(path, bounds)
            region.op(one, Region.Op.UNION)
        }
        muscle to region
    }.toMap()
}
